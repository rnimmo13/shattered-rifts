// Writes src/art/modelPixels.ts: for every pose-sheet model, the full height (in sheet pixels of the High set) its picture is fitted
// to, the same `fitH` heroSheet.ts works out. A figure is never shown taller than that at the screen's density, on every graphics
// setting alike, so the High set is drawn one to one and the setting changes only sharpness, never size (DECISIONS #793).
// Run before dev and build (package.json); `node scripts/model-pixels.mjs` by hand after packing new sheets.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const web = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const art = path.join(web, 'public', 'art');
/** the same as BODY_SHARE and MAX_WIDTH in src/fight/heroSheet.ts */
const BODY_SHARE = 0.78;
const MAX_WIDTH = 0.85;

const out = {};
const read = (dir) => {
  const file = path.join(dir, 'sprites.json');
  return fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, 'utf8')) : null;
};
const fit = (man, unit) => {
  const rest = man.clips.idle.frames[0];
  const scale = man.displayScale ?? 1;
  const h = rest[4] / scale;
  if (unit) return h;
  return Math.max(h / BODY_SHARE, (man.fitWidth ?? rest[3]) / scale / MAX_WIDTH);
};
const heroes = path.join(art, 'heroes-sheets');
for (const id of fs.readdirSync(heroes).sort()) {
  if (id === 'skins') {
    for (const skin of fs.readdirSync(path.join(heroes, 'skins')).sort()) {
      const man = read(path.join(heroes, 'skins', skin));
      if (man) out[`sheet:skins/${skin}`] = Math.round(fit(man, false));
    }
    continue;
  }
  const man = read(path.join(heroes, id));
  if (man) out[`sheet:${id}`] = Math.round(fit(man, false));
}
const units = path.join(art, 'units-sheets');
for (const id of fs.readdirSync(units).sort()) {
  const man = read(path.join(units, id));
  if (man) out[`unitsheet:${id}`] = Math.round(fit(man, true));
}

const body =
  "// Generated by scripts/model-pixels.mjs from the High sets: each pose-sheet model's fitted height in its own pixels\n" +
  '// (DECISIONS #793). Do not edit by hand.\n\n' +
  'export const MODEL_PIXELS: Readonly<Record<string, number>> = {\n' +
  Object.entries(out)
    .map(([k, v]) => `  '${k}': ${v},\n`)
    .join('') +
  '};\n';
const target = path.join(web, 'src', 'art', 'modelPixels.ts');
if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== body)
  fs.writeFileSync(target, body);
console.log(`model-pixels: ${Object.keys(out).length} models`);
