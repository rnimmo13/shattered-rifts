// `pnpm cardprompts:missing`: image prompts for every card a player can see that has no picture of its own: cards with no art at all,
// and cards that only borrowed a copy of another card's picture (DECISIONS #344). Grouped by Riftwalker, best cards first, nine to a
// sheet named <hero>-mNN. The sheets are added to docs/card-art/sheets.json (replacing earlier -mNN sheets), so tools/pack-cards.ps1
// cuts them like any other sheet; it runs them last, so a new picture replaces a borrowed copy. Writes docs/card-art/missing.md (every
// sheet) and docs/card-art/missing-batch-NN.md (sheet NN of every character). Run it again once some sheets are in: only cards that
// still need a picture are listed.

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { cardText } from '@sr/combat';
import { COMBAT_DB as db, RIFTWALKERS } from '@sr/content/v2';
import { KIND_HINT, OWN_LOOK, REALM_STYLE, strip } from './cardArtStyle';

interface Sheet {
  name: string;
  hero: string;
  cols: number;
  rows: number;
  ids: string[];
}

const SIZE = 9;
const RANK: Record<string, number> = {
  legendary: 0,
  ancestral: 0,
  rare: 1,
  uncommon: 2,
  common: 3,
  basic: 4,
};
const ART = new URL('../../apps/web/public/art/', import.meta.url);
const SHEETS = new URL('../../docs/card-art/sheets.json', import.meta.url);
const manifest = JSON.parse(readFileSync(new URL('manifest.json', ART), 'utf8')) as {
  cards: Record<string, string>;
};
const isMissingSheet = (name: string): boolean => /-m\d+$/.test(name);
const sheets = (JSON.parse(readFileSync(SHEETS, 'utf8')) as Sheet[]).filter(
  (s) => !isMissingSheet(s.name),
);

// every card a player can see: no upgrades or rolls (they share their base card's picture), no junk
const live = Object.values(db.cards).filter(
  (c) => !c.id.endsWith('+') && !c.id.includes('~') && !c.id.includes('^') && c.hero !== 'junk',
);
// a picture belongs to the card a sheet cut it for; another card showing the same picture only borrowed a copy
const onSheet = new Set(sheets.flatMap((s) => s.ids));
const hashOf = (file: string): string =>
  createHash('sha1')
    .update(readFileSync(new URL(file, ART)))
    .digest('hex');
const byHash = new Map<string, string[]>();
for (const c of live) {
  const file = manifest.cards[c.id];
  if (!file) continue;
  const h = hashOf(file);
  byHash.set(h, [...(byHash.get(h) ?? []), c.id]);
}
const borrowed = new Set<string>();
for (const ids of byHash.values())
  if (ids.length > 1) for (const id of ids) if (!onSheet.has(id)) borrowed.add(id);
const need = live.filter((c) => !manifest.cards[c.id] || borrowed.has(c.id));

const groups = new Map<string, typeof need>();
for (const c of need) {
  const h = c.hero && c.hero in RIFTWALKERS ? c.hero : 'neutral';
  groups.set(h, [...(groups.get(h) ?? []), c]);
}

const added: Sheet[] = [];
const files: string[] = [];
const batches = new Map<number, string[]>();
const index: string[] = [
  '# Card art: the cards still missing a picture (generated by `pnpm cardprompts:missing`: do not edit by hand)',
  '',
  `${need.length} cards: ${need.length - borrowed.size} with no picture, ${borrowed.size} showing a borrowed copy of another card's picture. Nine to a sheet, best cards first in each character.`,
  '',
  '## How to use',
  '1. Start with [missing-batch-01.md](missing-batch-01.md) (the first sheet of every character: their best cards). Paste ONE prompt at a time into the image AI and attach the Valeria image (`Sunlit Paladin with Shield and Sword.png`) as the style anchor.',
  '2. Check that the pictures are separate, in a clean 3 x 3 grid, with no text. If a picture is wrong, regenerate the whole sheet (I cut by position).',
  "3. Save the result as `assets-src/cards/<sheet name>.png` (the name is in each sheet's heading, for example `knight-m01`).",
  '4. Tell me which sheets are in: I cut them (`tools/pack-cards.ps1`) and run this tool again, so only what is still missing is listed.',
  '',
  '| Character | Cards | Sheets |',
  '|---|---|---|',
];
const order = ['neutral', ...Object.keys(RIFTWALKERS)];
for (const hero of order) {
  const list = groups.get(hero);
  if (!list?.length) continue;
  list.sort(
    (a, b) =>
      (RANK[a.rarity ?? 'common'] ?? 3) - (RANK[b.rarity ?? 'common'] ?? 3) ||
      a.name.localeCompare(b.name),
  );
  const r = hero in RIFTWALKERS ? RIFTWALKERS[hero as keyof typeof RIFTWALKERS] : null;
  const realm = r ? r.realm : 'neutral';
  const world = r
    ? `${OWN_LOOK[hero] ?? r.hero.name}. ${r.blurb} World: ${REALM_STYLE[realm]}.`
    : `Cards any Riftwalker can take. World: ${REALM_STYLE.neutral}.`;
  const title = r ? r.hero.name : 'Neutral';
  files.push(`## ${title}`, '');
  for (let i = 0; i < list.length; i += SIZE) {
    const chunk = list.slice(i, i + SIZE);
    const no = i / SIZE + 1;
    const name = `${hero}-m${String(no).padStart(2, '0')}`;
    const rows = Math.ceil(chunk.length / 3);
    added.push({ name, hero, cols: 3, rows, ids: chunk.map((c) => c.id) });
    const picture = chunk
      .map((c, n) => {
        const extra =
          c.rarity === 'legendary' || c.rarity === 'ancestral'
            ? ' Make it epic: glowing, richer detail, a grander composition.'
            : c.rarity === 'rare'
              ? ' A little more dramatic and detailed.'
              : '';
        return `${n + 1}. "${c.name}" (${c.kind === 'snare' ? 'trap' : c.kind === 'power' ? 'aura' : c.kind}): ${strip(cardText(db, c))} Show ${KIND_HINT[c.kind] ?? 'the idea'}.${extra}`;
      })
      .join('\n');
    const block = [
      `### Sheet \`${name}\` (${chunk.length} pictures, ${chunk[0]?.rarity ?? ''} first)`,
      '',
      '```',
      `Create ONE ILLUSTRATION SHEET of ${chunk.length} separate card-art pictures for a card-battler game (like Slay the Spire), 2400 x 1800, no text.`,
      'The attached image (Valeria) is the STYLE ANCHOR: match its cartoon game-art rendering exactly (bold clean dark outlines, flat saturated colours, simple cel shading, crisp polished shapes). Do NOT copy her character; paint scenes and objects. Backgrounds are softer and less contrasty than the main subject so the subject pops.',
      '',
      `LAYOUT (critical): a clean 3 x ${rows} grid of landscape 4:3 pictures (each about 760 x 570), separated by thin flat dark navy (#14181f) gutters, with NO frames, NO borders, NO captions, NO text, NO numbers. Every picture fills its own cell completely; nothing crosses a gutter. Each picture has ONE clear subject in the middle that reads at thumbnail size, a simple scene behind it, light from the upper left.${chunk.length % 3 ? ' Leave any unused cells plain dark navy.' : ''}`,
      '',
      `WORLD: ${world}`,
      '',
      'THE PICTURES, in this exact order, left to right, top row first. Use the card name and its effect only to decide what to draw; never write the name:',
      picture,
      '',
      'NEGATIVE: text, letters, numbers, captions, labels, UI, card frames, borders, watermark, logo, photorealism, gritty texture, nudity, characters facing away.',
      '```',
      '',
    ];
    files.push(...block);
    batches.set(no, [...(batches.get(no) ?? []), `## ${title}`, '', ...block]);
  }
  index.push(`| ${title} | ${list.length} | ${Math.ceil(list.length / SIZE)} |`);
}

index.push('', '## Batches', '', '| Batch | Sheets |', '|---|---|');
for (const [no, blocks] of batches) {
  const n = String(no).padStart(2, '0');
  const count = blocks.filter((l) => l.startsWith('### Sheet')).length;
  writeFileSync(
    new URL(`../../docs/card-art/missing-batch-${n}.md`, import.meta.url),
    [
      `# Missing card art, batch ${n} (${count} sheets)`,
      '',
      no === 1
        ? "Each character's most important missing cards (their Legendary and rare cards come first). Do this batch first."
        : `Sheet ${no} of every character that still has that many.`,
      '',
      'One prompt at a time: copy the text in ONE box, paste it, attach the Valeria image (`Sunlit Paladin with Shield and Sword.png`), and save the result as `assets-src/cards/<sheet name>.png`.',
      '',
      ...blocks,
    ].join('\n') + '\n',
  );
  index.push(`| [missing-batch-${n}.md](missing-batch-${n}.md) | ${count} |`);
}
index.push('', '# Every sheet', '', ...files);
writeFileSync(new URL('../../docs/card-art/missing.md', import.meta.url), index.join('\n') + '\n');
writeFileSync(SHEETS, JSON.stringify([...sheets, ...added], null, 1) + '\n');
console.log(
  `Wrote docs/card-art/missing.md and ${batches.size} batch files: ${need.length} cards (${borrowed.size} borrowed), ${added.length} sheets`,
);
