// `pnpm cardprompts`: writes docs/card-art/, ready-to-paste image prompts for card art, nine cards to a sheet. Basic and
// Common cards are left out on purpose (they keep their painted placeholder, or are drawn by hand): only Uncommon, Rare,
// Legendary and Ancestral cards get AI sheets. batch-01.md holds the first sheet of every character (the most important
// cards), batch-02.md the second, and so on, so a batch is a small, pasteable job.
// (a 3 x 3 grid), plus docs/card-art/sheets.json that tells tools/pack-cards.ps1 which card is in which cell of which sheet.
// Sheets are ordered best-first within each character (Legendary, Rare, Uncommon, Common, basics), so the first sheets
// of each file are the cards that matter most. Regenerate whenever the card pool changes.

import { mkdirSync, writeFileSync } from 'node:fs';
import { cardText } from '@sr/combat';
import { COMBAT_DB as db, RIFTWALKERS } from '@sr/content/v2';

const REALM_STYLE: Record<string, string> = {
  aurelion:
    'a gilded cathedral-castle: white marble, gold, royal blue, warm sunset light through stained glass',
  nexus:
    'a teal-and-orange foundry of machines: hazard stripes, steel, glowing cyan, sparks and steam',
  wyldmaw:
    'a primal jungle inside the ribcage of a giant beast: bone, crimson, moss green, bioluminescent mushrooms',
  umbral: 'a moonlit ballroom of shadows: violet and teal mist, masks, mirrors, candelabras',
  starfall:
    'a volcanic glass desert: black obsidian, ember-orange cracks, violet sheen, floating arcana stars',
  gloomfen: 'a drowned fen at night: pale green witch-light, bone, reeds, black water, mist',
  midden:
    "the rift's rubbish dump: rusty junk, green bottle glass, amber oil-drum firelight, a deep blue-black sky",
  neutral: 'the shattered rift between worlds: violet and cyan energy, floating broken stone',
};

const KIND_HINT: Record<string, string> = {
  attack: 'a dynamic strike caught mid-action',
  skill: 'a defensive or tactical moment, calm and clear',
  power: 'a grand symbolic still-life: one iconic object or pose that stands for the idea',
  summon: 'the creature or machine arriving, shown whole',
  snare: 'a hidden trap seen as it is being set, ominous',
};

const RANK: Record<string, number> = {
  legendary: 0,
  ancestral: 0,
  rare: 1,
  uncommon: 2,
};
/** the rarities that get AI art for now */
const ART_RARITIES = new Set(Object.keys(RANK));

const OWN_LOOK: Record<string, string> = {
  knight: 'Valeria, a blonde knight in blue-and-gold plate',
  engineer: 'Rivet, an engineer with a hovering drone',
  hunter: 'Kesh, a tribal huntress with bone weapons',
  trapper: 'Vesper, a masked trapper with teal glow',
  assassin: 'Sylas, a flamboyant rogue throwing teal-glowing knives',
  totemist: 'Ilvane, a spirit shaman who calls glowing totems',
  barbarian: 'Sehra, a flame-bound warrior with twin scimitars',
  spellblade: 'Obsidia, a queen of black volcanic glass with floating shards',
  necromancer: 'Mire, a spectral green-eyed reaper with thralls',
  drunkard: 'KP, a boisterous drunk dwarf with a shotgun and bottles',
};

const SIZE = 9;

interface Sheet {
  name: string;
  hero: string;
  cols: number;
  rows: number;
  ids: string[];
}

const strip = (t: string): string => t.replace(/\*\*/g, '').replace(/\s+/g, ' ').trim();

const cards = Object.values(db.cards).filter(
  (c) =>
    !c.id.endsWith('+') &&
    !c.id.includes('~') &&
    !c.unplayable &&
    c.hero !== 'junk' &&
    ART_RARITIES.has(c.rarity ?? 'common'),
);
const groups = new Map<string, typeof cards>();
for (const c of cards) {
  const h = c.hero && c.hero in RIFTWALKERS ? c.hero : 'neutral';
  (groups.get(h) ?? groups.set(h, []).get(h))?.push(c);
}

const sheets: Sheet[] = [];
/** sheet number (1, 2, 3...) -> that sheet of every character, as markdown blocks */
const batches = new Map<number, string[]>();
mkdirSync(new URL('../../docs/card-art/', import.meta.url), { recursive: true });
const index: string[] = [
  '# Card art prompts (generated by `pnpm cardprompts`: do not edit by hand)',
  '',
  `${cards.length} cards, nine to a sheet. One file per Riftwalker (plus Neutral). Inside each file the sheets run **best cards first** (Legendary, Rare, Uncommon, Common, basics), so if you only generate some, do the first sheets of each file.`,
  '',
  '## How to use',
  "1. Open a character's file, paste a sheet prompt into the image AI, and attach the Valeria image (`Sunlit Paladin with Shield and Sword.png`) as the style anchor.",
  '2. Check that the nine pictures are separate, in a clean 3 x 3 grid, with no text. If a picture is wrong, regenerate the whole sheet (the order matters, I cut by position).',
  "3. Save the result as `assets-src/cards/<sheet name>.png` (the name is in each sheet's heading, for example `knight-01`).",
  '4. Tell me which sheets are in, and I cut them into card art and wire them in (cards with no art keep their painted placeholder).',
  '',
  '| File | Cards | Sheets |',
  '|---|---|---|',
];
const batchRows: string[] = ['', '## Batches (start here)', '', '| Batch | Sheets |', '|---|---|'];

for (const [hero, list] of groups) {
  list.sort(
    (a, b) =>
      (RANK[a.rarity ?? 'common'] ?? 3) - (RANK[b.rarity ?? 'common'] ?? 3) ||
      a.name.localeCompare(b.name),
  );
  const r = hero in RIFTWALKERS ? RIFTWALKERS[hero as keyof typeof RIFTWALKERS] : null;
  const realm = r ? r.realm : 'neutral';
  const world = r
    ? `${OWN_LOOK[hero] ?? r.hero.name}. ${r.blurb} World: ${REALM_STYLE[realm]}.`
    : `Cards any Riftwalker can take. World: ${REALM_STYLE.neutral}.`;
  const out: string[] = [
    `# Card art: ${r ? r.hero.name : 'Neutral'}`,
    '',
    `${list.length} cards in ${Math.ceil(list.length / SIZE)} sheets. Anchor: attach the Valeria image to every prompt.`,
    '',
  ];
  for (let i = 0; i < list.length; i += SIZE) {
    const chunk = list.slice(i, i + SIZE);
    const name = `${hero}-${String(i / SIZE + 1).padStart(2, '0')}`;
    sheets.push({ name, hero, cols: 3, rows: 3, ids: chunk.map((c) => c.id) });
    const picture = chunk
      .map((c, n) => {
        const rare =
          c.rarity === 'legendary' || c.rarity === 'ancestral'
            ? ' Make it epic: glowing, richer detail, a grander composition.'
            : c.rarity === 'rare'
              ? ' A little more dramatic and detailed.'
              : '';
        return `${n + 1}. "${c.name}" (${c.kind}): ${strip(cardText(db, c))} Show ${KIND_HINT[c.kind] ?? 'the idea'}.${rare}`;
      })
      .join('\n');
    const block = [
      `## Sheet \`${name}\` (${chunk[0]?.rarity ?? ''} first)`,
      '',
      '```',
      `Create ONE ILLUSTRATION SHEET of ${chunk.length} separate card-art pictures for a card-battler game (like Slay the Spire), 2400 x 1800, no text.`,
      'The attached image (Valeria) is the STYLE ANCHOR: match its cartoon game-art rendering exactly (bold clean dark outlines, flat saturated colours, simple cel shading, crisp polished shapes). Do NOT copy her character; paint scenes and objects. Backgrounds are softer and less contrasty than the main subject so the subject pops.',
      '',
      'LAYOUT (critical): a clean 3 x 3 grid of landscape 4:3 pictures (each about 760 x 570), separated by thin flat dark navy (#14181f) gutters, with NO frames, NO borders, NO captions, NO text, NO numbers. Every picture fills its own cell completely; nothing crosses a gutter. Each picture has ONE clear subject in the middle that reads at thumbnail size, a simple scene behind it, light from the upper left.',
      '',
      `WORLD: ${world}`,
      '',
      'THE PICTURES, in this exact order, left to right, top row first. Use the card name and its effect only to decide what to draw; never write the name:',
      picture,
      '',
      'NEGATIVE: text, letters, numbers, captions, labels, UI, card frames, borders, watermark, logo, photorealism, gritty texture, nudity, characters facing away.',
      '```',
      '',
    ];
    out.push(...block);
    const no = i / SIZE + 1;
    batches.set(no, [
      ...(batches.get(no) ?? []),
      `### ${r ? r.hero.name : 'Neutral'}`,
      '',
      ...block,
    ]);
  }
  writeFileSync(new URL(`../../docs/card-art/${hero}.md`, import.meta.url), out.join('\n'));
  index.push(`| [${hero}.md](${hero}.md) | ${list.length} | ${Math.ceil(list.length / SIZE)} |`);
}

for (const [no, blocks] of batches) {
  const n = String(no).padStart(2, '0');
  const count = blocks.filter((l) => l.startsWith('## Sheet')).length;
  writeFileSync(
    new URL(`../../docs/card-art/batch-${n}.md`, import.meta.url),
    [
      `# Card art, batch ${n} (${count} sheets)`,
      '',
      no === 1
        ? "The most important cards: every character's Legendary and best Rare cards. Do this batch first."
        : `Sheet ${no} of every character.`,
      '',
      'One prompt at a time: copy the text in ONE box, paste it, attach the Valeria image (`Sunlit Paladin with Shield and Sword.png`), and save the result as `assets-src/cards/<sheet name>.png` (the name is in the heading). Do not paste the whole file at once.',
      '',
      ...blocks,
    ].join('\n') + '\n',
  );
  batchRows.push(`| [batch-${n}.md](batch-${n}.md) | ${count} |`);
}
writeFileSync(
  new URL('../../docs/card-art/README.md', import.meta.url),
  [...index, ...batchRows].join('\n') + '\n',
);
writeFileSync(
  new URL('../../docs/card-art/sheets.json', import.meta.url),
  JSON.stringify(sheets, null, 1) + '\n',
);
console.log(`Wrote docs/card-art/ (${cards.length} cards, ${sheets.length} sheets)`);
