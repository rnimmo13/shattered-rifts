// `pnpm artlist`: writes docs/art-briefs.md, a ready-to-use list of every piece of artwork the game wants, with an
// image prompt for each (cards, Riftwalkers, companions, enemies, Boons, Potions). Regenerate it whenever content changes.
// See docs/09_ART_BRIEF_V2.md for the style guide, sizes and how finished files are added.

import { writeFileSync } from 'node:fs';
import { cardText } from '@sr/combat';
import { BOONS, COMBAT_DB as db, ENCOUNTERS, POTIONS, RIFTWALKERS } from '@sr/content/v2';

const REALM_STYLE: Record<string, string> = {
  aurelion:
    'gilded cathedral knights, warm gold light through stained glass, ivory and royal blue, holy and severe',
  nexus:
    'rusted foundry machines, teal and orange sparks, conveyor belts, cold steel, hard industrial light',
  wyldmaw:
    'bioluminescent jungle ribcage, blood red and acid green, feral and hungry, bone and teeth',
  umbral: 'moonlit ballroom of shadows, violet and teal mist, masks and mirrors, quiet menace',
  starfall:
    'a night sky of fallen stars, deep indigo and pale gold, scholars of constellations, silver circlets and astrolabes',
  gloomfen:
    'a drowned fen of green witch-light, bone and reeds, quiet wardens of the dead, pale mist over black water',
  midden:
    "the rift's rubbish heap: rusted trolleys, broken windows and green bottle glass, amber firelight in an oil drum, a drunk's kingdom of junk",
  neutral: 'a shattered rift between worlds, violet and cyan energy, fractured crystal',
  junk: 'a dull grey curse, scratched and dim',
};

const STYLE =
  'dark-fantasy painterly illustration, bold readable silhouette, rich colour, soft rim light, no text, no border';

const lines: string[] = [
  '# Art briefs (generated by `pnpm artlist`: do not edit by hand)',
  '',
  `Style for everything: ${STYLE}. Realm flavours are below each section. Card art is a **4:3 window** (about 1024x768); figures are **transparent PNG cut-outs**, feet on the bottom edge, about 1024 px tall.`,
  '',
  '## Riftwalkers (figures, `hero:<id>`)',
  '',
];
for (const [id, r] of Object.entries(RIFTWALKERS)) {
  lines.push(
    `- **${r.hero.name}** (\`hero:${id}\`, ${r.realm}): ${r.blurb} Prompt: "full-body hero, ${REALM_STYLE[r.realm]}, ${STYLE}, transparent background"`,
  );
}

lines.push('', '## Companions and enemies (figures, `unit:<id>`)', '');
const seen = new Set<string>();
for (const e of ENCOUNTERS) {
  for (const u of e.units) {
    if (seen.has(u)) continue;
    seen.add(u);
    const d = db.units[u];
    if (!d) continue;
    const realm = e.realm === 'all' ? 'neutral' : e.realm;
    lines.push(
      `- **${d.name}** (\`unit:${u}\`, ${e.kind}, ${d.maxHp} HP): Prompt: "${d.name}, ${REALM_STYLE[realm]}, ${STYLE}, transparent background, ${e.kind === 'warden' || e.kind === 'finale' ? 'imposing boss' : e.kind === 'elite' ? 'dangerous elite' : 'standard foe'}"`,
    );
  }
}
for (const [id, d] of Object.entries(db.units)) {
  if (d.brain.kind !== 'ally' || id.endsWith('+')) continue;
  lines.push(
    `- **${d.name}** (\`unit:${id}\`, companion): Prompt: "${d.name}, small loyal companion, ${STYLE}, transparent background"`,
  );
}

lines.push('', '## Cards (art windows, `cards/<id>`)', '');
for (const c of Object.values(db.cards)) {
  if (c.id.endsWith('+') || c.unplayable) continue;
  const realm = c.realm ?? 'neutral';
  lines.push(
    `- **${c.name}** (\`${c.id}\`, ${c.kind}, ${realm}): ${cardText(db, c)} Prompt: "${c.name}: ${cardText(db, c).replace(/\*\*/g, '')} ${REALM_STYLE[realm] ?? ''}, ${STYLE}, 4:3"`,
  );
}

lines.push('', '## Boons (icons, `boons/<id>`, 256 px, transparent)', '');
for (const b of BOONS)
  lines.push(
    `- **${b.name}** (\`${b.id}\`, ${b.rarity}): ${b.text} Prompt: "${b.name} relic icon, ${STYLE}"`,
  );
lines.push('', '## Potions (icons, `potions/<id>`, 256 px, transparent)', '');
for (const p of POTIONS)
  lines.push(
    `- **${p.name}** (\`${p.id}\`, ${p.rarity}): ${p.text} Prompt: "${p.name} potion bottle icon, ${STYLE}"`,
  );

lines.push('', '## Backdrops (`backdrops/<realm>`, 1920x1080)', '');
for (const realm of ['aurelion', 'nexus', 'wyldmaw', 'umbral', 'neutral'])
  lines.push(
    `- **${realm}**: Prompt: "wide battle arena, ${REALM_STYLE[realm]}, ${STYLE}, empty flat floor for characters in the lower third, 16:9"`,
  );

writeFileSync(new URL('../../docs/art-briefs.md', import.meta.url), lines.join('\n') + '\n');
console.log(`Wrote docs/art-briefs.md (${lines.length} lines)`);
