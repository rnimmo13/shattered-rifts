// `pnpm cardprompts:extra`: image prompts for the Uncommon, Rare, Legendary and Ancestral cards that no sheet covers yet (cards added
// after the sheets were made, and cards the main tool skips, like discard-only cards). The existing sheets are never touched: the new
// cards go on extra sheets (extra-01, extra-02...), listed in docs/card-art/sheets.json so tools/pack-cards.ps1 cuts them like any other
// sheet. Pictures of different Riftwalkers share a sheet, each with its own world noted in brackets. Safe to run again: only cards that
// are still uncovered are added; docs/card-art/extra.md always holds the prompt of every extra sheet.

import { readFileSync, writeFileSync } from 'node:fs';
import { cardText } from '@sr/combat';
import { COMBAT_DB as db, RIFTWALKERS } from '@sr/content/v2';
import { KIND_HINT, OWN_LOOK, REALM_STYLE, strip } from './cardArtStyle';

interface Sheet {
  name: string;
  hero: string;
  cols: number;
  rows: number;
  ids: string[];
}

const SIZE = 9;
const RARITIES = ['uncommon', 'rare', 'legendary', 'ancestral'];
const SHEETS = new URL('../../docs/card-art/sheets.json', import.meta.url);
const sheets = JSON.parse(readFileSync(SHEETS, 'utf8')) as Sheet[];
const covered = new Set(sheets.flatMap((s) => s.ids));

/** what to paint for cards whose kind says little (discard-only cards, the cleansing line): by card id */
const SCENE: Record<string, string> = {
  'purging-light':
    'a pillar of white-gold light washing dark chains and curse-smoke off a kneeling silhouette, bright and clean',
  'steady-nerves':
    'a calm steady hand held out, a deep breath, dark jittery mist fading from it into clear air',
  'ace-up-the-sleeve':
    'a playing card flicked out of a sleeve with a flourish, caught mid-flip, a sly grin in the shadows',
  'loaded-die': 'a heavy weighted die tumbling across a table and bursting into a ring of teal sparks',
  'pilfered-time':
    'a stolen pocket watch dangling from nimble fingers, its hands blurred, sand of time spilling',
  'jokers-gambit':
    'a grinning joker card thrown to the floor and blossoming into three glowing teal knives',
};

const missing = Object.values(db.cards)
  .filter(
    (c) =>
      !c.id.endsWith('+') &&
      !c.id.includes('~') &&
      c.hero !== 'junk' &&
      RARITIES.includes(c.rarity ?? '') &&
      !covered.has(c.id),
  )
  .sort(
    (a, b) =>
      RARITIES.indexOf(b.rarity ?? '') - RARITIES.indexOf(a.rarity ?? '') ||
      String(a.hero).localeCompare(String(b.hero)) ||
      a.name.localeCompare(b.name),
  );

const worldOf = (hero: string | undefined): string => {
  const r = hero && hero in RIFTWALKERS ? RIFTWALKERS[hero as keyof typeof RIFTWALKERS] : null;
  return r
    ? `${OWN_LOOK[hero as string] ?? r.hero.name}; ${REALM_STYLE[r.realm]}`
    : (REALM_STYLE['neutral'] as string);
};

// the new cards go on new extra sheets (nine to a sheet)
const existing = sheets.filter((s) => s.name.startsWith('extra-'));
const added: Sheet[] = [];
for (let i = 0; i < missing.length; i += SIZE)
  added.push({
    name: `extra-${String(existing.length + i / SIZE + 1).padStart(2, '0')}`,
    hero: 'mixed',
    cols: 3,
    rows: Math.ceil(Math.min(SIZE, missing.length - i) / 3),
    ids: missing.slice(i, i + SIZE).map((c) => c.id),
  });
const all = [...existing, ...added];
if (all.length === 0) {
  console.log('Every Uncommon, Rare, Legendary and Ancestral card is on a sheet already.');
  process.exit(0);
}

const out: string[] = [
  '# Card art: extra sheets (generated by `pnpm cardprompts:extra`)',
  '',
  'Cards that were added after the main sheets, or that the main tool skips. Paste ONE prompt, attach the Valeria image (`Sunlit Paladin with Shield and Sword.png`), and save the result as `assets-src/cards/<sheet name>.png`. Then tell me, and I cut it.',
  '',
];
for (const sheet of all) {
  const chunk = sheet.ids
    .map((id) => db.cards[id])
    .filter((c): c is NonNullable<typeof c> => c !== undefined);
  const picture = chunk
    .map((c, n) => {
      const more =
        c.rarity === 'legendary' || c.rarity === 'ancestral'
          ? ' Make it epic: glowing, richer detail, a grander composition.'
          : c.rarity === 'rare'
            ? ' A little more dramatic and detailed.'
            : '';
      const text = strip(cardText(db, c)) || 'A card that does something when it is discarded.';
      const show = SCENE[c.id] ?? KIND_HINT[c.kind] ?? 'the idea';
      return `${n + 1}. "${c.name}" (${c.kind}): ${text} Show ${show}.${more} [World: ${worldOf(c.hero)}.]`;
    })
    .join('\n');
  out.push(
    `## Sheet \`${sheet.name}\` (${chunk.length} pictures)`,
    '',
    '```',
    `Create ONE ILLUSTRATION SHEET of ${chunk.length} separate card-art pictures for a card-battler game (like Slay the Spire), 2400 x 1800, no text.`,
    'The attached image (Valeria) is the STYLE ANCHOR: match its cartoon game-art rendering exactly (bold clean dark outlines, flat saturated colours, simple cel shading, crisp polished shapes). Do NOT copy her character; paint scenes and objects. Backgrounds are softer and less contrasty than the main subject so the subject pops.',
    '',
    'LAYOUT (critical): a clean 3 x 3 grid of landscape 4:3 pictures (each about 760 x 570), separated by thin flat dark navy (#14181f) gutters, with NO frames, NO borders, NO captions, NO text, NO numbers. Every picture fills its own cell completely; nothing crosses a gutter. Each picture has ONE clear subject in the middle that reads at thumbnail size, a simple scene behind it, light from the upper left. Leave any unused cells plain dark navy.',
    '',
    'WORLD: each picture has its own world, given in [brackets] after it; paint that picture in that world. Do not write the brackets.',
    '',
    'THE PICTURES, in this exact order, left to right, top row first. Use the card name and its effect only to decide what to draw; never write the name:',
    picture,
    '',
    'NEGATIVE: text, letters, numbers, captions, labels, UI, card frames, borders, watermark, logo, photorealism, gritty texture, nudity, characters facing away.',
    '```',
    '',
  );
}
writeFileSync(new URL('../../docs/card-art/extra.md', import.meta.url), out.join('\n'));
if (added.length > 0) writeFileSync(SHEETS, JSON.stringify([...sheets, ...added], null, 1) + '\n');
console.log(
  `Wrote docs/card-art/extra.md: ${all.length} extra sheet(s) (${all.map((s) => s.name).join(', ')}), ${added.length} new.`,
);
