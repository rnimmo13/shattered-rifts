// `pnpm cardlist`: writes docs/10_CARD_LIST.md, every card of every Riftwalker with its rules text, generated from the
// real card data (so it never drifts). Cards are grouped by pool; "+" versions are not listed.

import { writeFileSync } from 'node:fs';
import { cardText } from '@sr/combat';
import { COMBAT_DB as db, RIFTWALKERS, type HeroId } from '@sr/content/v2';

const cards = Object.values(db.cards).filter((c) => !c.id.endsWith('+') && c.hero !== 'junk');
const order = { basic: 0, common: 1, uncommon: 2, rare: 3, legendary: 4, ancestral: 5 } as const;

const row = (c: (typeof cards)[number]): string => {
  const cost = c.x
    ? 'X'
    : String(c.cost) +
      (c.starCost ? `+${c.starCost}◆` : '') +
      (c.statusCost
        ? ` + ${c.statusCost.x ? 'X' : c.statusCost.amount} ${c.statusCost.status[0]!.toUpperCase()}${c.statusCost.status.slice(1)}`
        : '');
  const text = cardText(db, c).replace(/\|/g, '/');
  return `| ${c.name} | ${cost} | ${c.kind === 'snare' ? 'trap' : c.kind === 'power' ? 'aura' : c.kind} | ${c.rarity ?? ''} | ${text} |`;
};

const table = (list: typeof cards): string[] => [
  '| Card | Cost | Type | Rarity | Text |',
  '|---|---|---|---|---|',
  ...[...list].sort((a, b) => order[a.rarity ?? 'common'] - order[b.rarity ?? 'common']).map(row),
  '',
];

const out: string[] = [
  '# Card list (generated by `pnpm cardlist`: do not edit by hand)',
  '',
  `${cards.length} cards. Design rules for pools are in \`09_ROSTER.md\`.`,
  '',
];

for (const [id, r] of Object.entries(RIFTWALKERS)) {
  const pool = cards.filter((c) => c.hero === id && !c.source);
  out.push(`## ${r.hero.name} (${r.realm}, ${r.hero.maxHp} HP)`, '', r.blurb, '');
  out.push(`Starter: ${r.starter.map((s) => db.cards[s]?.name ?? s).join(', ')}`, '');
  out.push(...table(pool));
  const tokens = cards.filter((c) => c.hero === id && c.source === 'token');
  if (tokens.length) out.push('Tokens (made by other cards):', '', ...table(tokens));
}
out.push('## Neutral', '', ...table(cards.filter((c) => c.hero === 'neutral' && !c.source)));
out.push(
  '## Warden signature cards',
  '',
  ...table(cards.filter((c) => c.source?.startsWith('boss:'))),
);

const count = (h: HeroId): number => cards.filter((c) => c.hero === h && !c.source).length;
out.push(
  '## Pool sizes',
  '',
  ...(Object.keys(RIFTWALKERS) as HeroId[]).map((h) => `- ${h}: ${count(h)}`),
  '',
);

writeFileSync(new URL('../../docs/10_CARD_LIST.md', import.meta.url), out.join('\n'));
console.log(`Wrote docs/10_CARD_LIST.md (${cards.length} cards)`);
