// `pnpm poolaudit`: each Riftwalker's pool by build path and rarity, with near-duplicates flagged: two cards of the same pool with the
// same type, the same cost and the same effects in the same order, whose numbers differ by about a third or less. Writes
// docs/POOL_AUDIT.md (Robert, 2026-10-27: "definitely dont want any near duplicates and most of them should fall into one of the build paths").
//
//   pnpm poolaudit

import { writeFileSync } from 'node:fs';
import { cardText, type CardDef, type Op } from '@sr/combat';
import { COMBAT_DB as db, RIFTWALKERS, pathName, pathOf, type HeroId } from '@sr/content/v2';

const RANKS = ['basic', 'common', 'uncommon', 'rare', 'legendary'];

/** What a card does, without its numbers: kind, cost and each op with its target, status and scale. */
function shape(c: CardDef): string {
  const op = (o: Op): string => {
    const r = o as Record<string, unknown>;
    const scale = r['scale'] as { by?: string } | undefined;
    const inner = o.op === 'power' ? `[${o.when}:${o.ops.map(op).join(',')}]` : '';
    return [o.op, r['to'], r['status'], r['when'], r['unit'], r['card'], scale?.by, inner]
      .filter(Boolean)
      .join('/');
  };
  return `${c.kind}|${c.cost}|${c.statusCost ? 'sc' : ''}${c.starCost ? 'st' : ''}|${c.effects.map(op).join(';')}`;
}
/** Every number a card's effects hold, in order (amounts, hits, scale factors). */
function numbers(c: CardDef): number[] {
  const out: number[] = [];
  const walk = (o: Op): void => {
    const r = o as Record<string, unknown>;
    for (const k of ['amount', 'hits', 'times', 'mult', 'max'])
      if (typeof r[k] === 'number') out.push(r[k]);
    const sc = r['scale'] as { mult?: number } | undefined;
    if (sc?.mult !== undefined) out.push(sc.mult);
    if (o.op === 'power') o.ops.forEach(walk);
  };
  c.effects.forEach(walk);
  return out;
}
const close = (a: number[], b: number[]): boolean =>
  a.length === b.length &&
  a.every((x, i) => {
    const y = b[i] as number;
    return Math.abs(x - y) <= Math.max(1, Math.max(Math.abs(x), Math.abs(y)) / 3);
  });

const lines: string[] = [
  '# Pool audit',
  '',
  "Generated by `pnpm poolaudit`. Each Riftwalker's cards by build path; **near-duplicates** are two cards of one pool with the same type,",
  'cost and effects whose numbers differ by about a third or less. "Shared" cards belong to no build path (basics and glue).',
  '',
];
let dupTotal = 0;
for (const h of Object.keys(RIFTWALKERS) as HeroId[]) {
  const cards = Object.values(db.cards).filter(
    (c) => c.hero === h && !c.id.endsWith('+') && !c.source && c.rarity !== 'basic',
  );
  const groups = new Map<string, CardDef[]>();
  for (const c of cards) groups.set(shape(c), [...(groups.get(shape(c)) ?? []), c]);
  const dups: string[] = [];
  for (const g of groups.values())
    for (let i = 0; i < g.length; i++)
      for (let j = i + 1; j < g.length; j++)
        if (close(numbers(g[i] as CardDef), numbers(g[j] as CardDef)))
          dups.push(
            `- **${g[i]!.name}** and **${g[j]!.name}**: ${cardText(db, g[i]!)} / ${cardText(db, g[j]!)}`,
          );
  dupTotal += dups.length;
  const byPath = (p: number | undefined) => cards.filter((c) => pathOf(c.id) === p);
  const shared = cards.filter((c) => pathOf(c.id) === undefined);
  lines.push(
    `## ${RIFTWALKERS[h].hero.name} (${h})`,
    '',
    `${cards.length} cards: ${RIFTWALKERS[h].buildPaths.map((_, p) => `${pathName(h, p)} ${byPath(p).length}`).join(', ')}, shared ${shared.length}.`,
    '',
  );
  if (dups.length) lines.push('**Near-duplicates:**', '', ...dups, '');
  for (const [label, list] of [
    ...RIFTWALKERS[h].buildPaths.map((_, p) => [pathName(h, p), byPath(p)] as const),
    ['Shared', shared] as const,
  ]) {
    lines.push(
      `### ${label}`,
      '',
      '| Card | Rarity | Type | Cost | Text |',
      '|---|---|---|---|---|',
    );
    for (const c of [...list].sort(
      (a, b) =>
        RANKS.indexOf(a.rarity ?? 'common') - RANKS.indexOf(b.rarity ?? 'common') ||
        a.name.localeCompare(b.name),
    ))
      lines.push(
        `| ${c.name} | ${c.rarity} | ${c.kind === 'snare' ? 'trap' : c.kind === 'power' ? 'aura' : c.kind} | ${c.cost}${c.statusCost ? ` +${c.statusCost.x ? 'X' : c.statusCost.amount} ${c.statusCost.status}` : ''}${c.starCost ? ` +${c.starCost} Arcana` : ''} | ${cardText(db, c).replace(/\|/g, '/')} |`,
      );
    lines.push('');
  }
}
writeFileSync('../docs/POOL_AUDIT.md', lines.join('\n'));
console.log(`Wrote docs/POOL_AUDIT.md (${dupTotal} near-duplicate pairs)`);
