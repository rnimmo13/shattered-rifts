// `pnpm --filter @sr/tools exec tsx src/ledger/write.ts <class>`: writes docs/reworks/<class>-ledger.md, the hand-balance ledger of a
// rebuilt class: every card and its upgrade with its live text, the hand price from ledger/<class>.ts, the budget the costing guide
// gives it, and the deviation. It fails (exit 1) if a card has no price, a price names no card, a card is more than 15% off budget
// without a reason, or an upgrade adds more than half again.

import { writeFileSync } from 'node:fs';
import { cardText } from '@sr/combat';
import { COMBAT_DB as db, pathOf, pathName, RIFTWALKERS, type HeroId } from '@sr/content/v2';
import { budgetOf, pct, type Price } from './common';
import { ASSASSIN_PRICES } from './assassin';
import { KNIGHT_PRICES } from './knight';
import { MONK_PRICES } from './monk';
import { SHAMAN_PRICES } from './shaman';
import { SPELLBLADE_PRICES } from './spellblade';

const PRICES: Partial<Record<HeroId, Record<string, Price>>> = {
  knight: KNIGHT_PRICES,
  assassin: ASSASSIN_PRICES,
  spellblade: SPELLBLADE_PRICES,
  shaman: SHAMAN_PRICES,
  monk: MONK_PRICES,
};

const hero = process.argv[2] as HeroId;
const prices = PRICES[hero];
if (!prices) throw new Error(`no ledger for "${hero}"`);
const r = RIFTWALKERS[hero];

const order = { basic: 0, common: 1, uncommon: 2, rare: 3, legendary: 4, ancestral: 5 } as const;
const cards = Object.values(db.cards)
  .filter((c) => c.hero === hero && !c.id.endsWith('+') && !c.source)
  .sort(
    (a, b) =>
      order[a.rarity ?? 'common'] - order[b.rarity ?? 'common'] ||
      (pathOf(a.id) ?? 9) - (pathOf(b.id) ?? 9) ||
      a.cost - b.cost ||
      (a.id < b.id ? -1 : 1),
  );

const problems: string[] = [];
for (const id of Object.keys(prices))
  if (!cards.some((c) => c.id === id)) problems.push(`price for unknown card ${id}`);
const rows: string[] = [];
let within = 0;
for (const c of cards) {
  const p = prices[c.id];
  if (!p) {
    problems.push(`no price for ${c.id}`);
    continue;
  }
  const up = c.upgrade ? db.cards[c.upgrade] : undefined;
  const b = budgetOf(c, p);
  const dev = p.pts / b - 1;
  const gain = p.up / p.pts - 1;
  if (Math.abs(dev) > 0.15 && !p.why)
    problems.push(`${c.id} is ${pct(p.pts, b)} off budget with no reason`);
  if (gain > 0.5) problems.push(`${c.id}+ adds ${Math.round(gain * 100)}%`);
  if (gain <= 0) problems.push(`${c.id}+ is not better`);
  if (Math.abs(dev) <= 0.15) within++;
  const path = pathOf(c.id);
  const cell = (s: string): string => s.replace(/\|/g, '/');
  rows.push(
    `| \`${c.id}\` | ${c.name} | ${path === undefined ? 'glue' : pathName(hero, path)} | ${c.rarity} | ${c.x ? 'X' : c.cost}${c.kind === 'power' ? ' Aura' : ''} | ${cell(cardText(db, c))} | ${cell(p.how)} | ${p.pts} | ${b} | ${pct(p.pts, b)} | ${up ? `${cell(cardText(db, up))}${up.cost !== c.cost ? ` (cost ${up.cost})` : ''}${up.innate && !c.innate ? ' (Opening hand)' : ''}` : 'none'} | ${p.up} (${gain >= 0 ? '+' : ''}${Math.round(gain * 100)}%) | ${cell(p.role)}${p.why ? ` *Off budget because:* ${cell(p.why)}` : ''} |`,
  );
}

const md = [
  `# ${r.hero.name}: the balance ledger (generated by \`tools/src/ledger/write.ts ${hero}\`; do not edit by hand)`,
  '',
  `Hand prices from \`tools/src/ledger/${hero}.ts\`, against the budgets of docs/14_CARD_COSTING.md (1 Mana common = 10, then +9 a Mana; uncommon x1.12, rare x1.25, basic x0.8; an Aura over four turns at 1.5x (uncommon) or 2x (rare) its cost's budget; Consume +25%). The new rates are in the guide's §15. These are hypotheses for hand balance, not measured win rates.`,
  '',
  `${cards.length} cards; ${within} within ±15% of budget, the rest explained in the last column.`,
  '',
  '| Id | Card | Strategy | Rarity | Cost | Text | Price | Points | Budget | Off | Upgrade | Upgrade points | Role, package and notes |',
  '|---|---|---|---|---|---|---|---|---|---|---|---|---|',
  ...rows,
  '',
].join('\n');
writeFileSync(`../docs/reworks/${hero}-ledger.md`, md);
console.log(`${hero}: ${cards.length} cards, ${within} within ±15%`);
if (problems.length) {
  console.log(problems.join('\n'));
  process.exitCode = 1;
}
