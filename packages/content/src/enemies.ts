// Enemy duelists, Elites, Wardens and the finale (03_CAMPAIGN §4). Decks are authored from each
// theme using realm + Neutral cards. Warden Omens / signature mechanics / phases are boss scripts
// (M5); here they only carry the deck, Essence and an AI personality.

export type EnemyKind = 'regular' | 'elite' | 'warden' | 'finale';
export type EnemyRealm = 'aurelion' | 'nexus' | 'wyldmaw' | 'umbral' | 'all';

/** Mirrors the AI package's personality ids (checked by a test). */
export type EnemyPersonality = 'balanced' | 'aggressive' | 'controlling' | 'trappy' | 'novice';

export interface EnemyDef {
  id: string;
  name: string;
  realm: EnemyRealm;
  kind: EnemyKind;
  /** Starting Essence at Rift Tier I. */
  essence: number;
  personality: EnemyPersonality;
  theme: string;
  deck: Record<string, number>;
}

export const deckList = (e: EnemyDef): string[] =>
  Object.entries(e.deck).flatMap(([card, n]) => Array.from({ length: n }, () => card));

const regular = (
  id: string,
  name: string,
  realm: EnemyRealm,
  personality: EnemyPersonality,
  theme: string,
  deck: Record<string, number>,
): EnemyDef => ({ id, name, realm, kind: 'regular', essence: 14, personality, theme, deck });

const elite = (
  id: string,
  name: string,
  realm: EnemyRealm,
  personality: EnemyPersonality,
  theme: string,
  deck: Record<string, number>,
): EnemyDef => ({ id, name, realm, kind: 'elite', essence: 30, personality, theme, deck });

